#!/usr/bin/env python3
"""Packs the output of native runs of chaos.c into ../native_runs.h, the data
the voter's page replays.

  pack.py <label>=<output of "chaos 40"> ... > ../native_runs.h

Each run gives theta1 and theta2 every 40 steps, as 16-bit fractions of a
turn (angle mod 2 pi), little-endian, base64 per run, and the bits of theta1
at every 2000th step as the program prints them.
"""
import base64
import math
import struct
import sys


def read(path):
    samples, bits = [], []
    for line in open(path):
        f = line.split()
        if f[0] == "s":
            samples.append((int(f[1]), float.fromhex(f[2]), float.fromhex(f[3])))
        elif len(f) == 3:
            bits.append((int(f[0]), f[2]))
    return samples, bits


def turn(a):
    return int(round((a % (2 * math.pi)) / (2 * math.pi) * 65536)) & 0xFFFF


def main():
    runs = []
    every = None
    for arg in sys.argv[1:]:
        label, path = arg.split("=", 1)
        samples, bits = read(path)
        steps = [s for s, _, _ in samples]
        step = steps[1] - steps[0]
        if every is None:
            every = step
        if step != every or steps[0] != every:
            sys.exit("%s: samples every %d steps, from step %d; want every %d from %d" % (path, step, steps[0], every, every))
        raw = b"".join(struct.pack("<HH", turn(t1), turn(t2)) for _, t1, t2 in samples)
        runs.append((label, base64.b64encode(raw).decode(), bits))
    js = ["NATIVE={every:%d,runs:[" % every]
    for label, b64, bits in runs:
        js.append("{label:'%s',bits:[%s],a:'%s'}," % (label, ",".join("[%d,'%s']" % b for b in bits), b64))
    js.append("]};")
    text = "".join(js)
    out = ["/* Generated by native/pack.py from native runs of native/chaos.c; see",
           " * apps/voter/README.md (Native runs). */",
           "static const char native_runs_js[] ="]
    for i in range(0, len(text), 100):
        out.append('    "%s"' % text[i:i + 100])
    out[-1] += ";"
    print("\n".join(out))


if __name__ == "__main__":
    main()
