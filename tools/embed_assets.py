#!/usr/bin/env python3
"""
Generates the embedded blob tables for the local image registry and the
static bundles served by the ingress controller.

Inputs (relative to the repository root):
  images/*.wasm                     -> EmbeddedImage entries, key = file stem
  images/web/<bundle>/<path>[.gz]   -> EmbeddedAsset entries for bundle <bundle>,
                                       path = /<path> without ".gz"; a ".gz" file
                                       is served with Content-Encoding: gzip. A
                                       file may exist both plain and as .gz: the
                                       server picks by the client's Accept-Encoding.

Outputs:
  <out_dir>/embedded_blobs.cpp  host build: byte arrays generated inline
  src/embedded/embedded_blobs_esp.cpp  firmware: tables over EMBED_FILES symbols
  src/embedded/embedded_files.cmake    firmware: list consumed by src/CMakeLists.txt

Usage:
  tools/embed_assets.py --host-out build/generated
  tools/embed_assets.py --esp
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMAGES_DIR = os.path.join(ROOT, "images")
WEB_DIR = os.path.join(IMAGES_DIR, "web")

CONTENT_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".txt": "text/plain; charset=utf-8",
    ".mjs": "application/javascript; charset=utf-8",
    ".map": "application/json",
    ".webmanifest": "application/manifest+json",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".webp": "image/webp",
    ".gif": "image/gif",
    ".wasm": "application/wasm",
    ".woff": "font/woff",
    ".woff2": "font/woff2",
}


def collect():
    images = []
    assets = []
    if os.path.isdir(IMAGES_DIR):
        for name in sorted(os.listdir(IMAGES_DIR)):
            if name.endswith(".wasm"):
                images.append((name[:-5], os.path.join(IMAGES_DIR, name)))
    if os.path.isdir(WEB_DIR):
        for bundle in sorted(os.listdir(WEB_DIR)):
            bundle_dir = os.path.join(WEB_DIR, bundle)
            if not os.path.isdir(bundle_dir):
                continue
            seen = {}
            for dirpath, dirnames, filenames in os.walk(bundle_dir):
                dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
                for name in sorted(filenames):
                    if name.startswith("."):
                        continue
                    full = os.path.join(dirpath, name)
                    rel = os.path.relpath(full, bundle_dir).replace(os.sep, "/")
                    gz = rel.endswith(".gz")
                    plain = rel[:-3] if gz else rel
                    ext = os.path.splitext(plain)[1].lower()
                    ctype = CONTENT_TYPES.get(ext, "application/octet-stream")
                    path = "/" + plain
                    if '"' in path or "\\" in path:
                        sys.exit(f"[embed] {bundle}: unsupported character in {rel}")
                    if (path, gz) in seen:
                        sys.exit(f"[embed] {bundle}: both {seen[(path, gz)]} and {rel} map to {path}")
                    seen[(path, gz)] = rel
                    assets.append((bundle, path, full, ctype, gz))
    return images, assets


def sym(path):
    # ESP-IDF turns the basename into a symbol: dots and dashes become underscores
    base = os.path.basename(path)
    return "".join(c if c.isalnum() else "_" for c in base)


def write_host(out_dir, images, assets):
    os.makedirs(out_dir, exist_ok=True)
    out = os.path.join(out_dir, "embedded_blobs.cpp")
    with open(out, "w") as f:
        f.write("// Generated by tools/embed_assets.py. Do not edit.\n")
        f.write("#include \"embedded/embedded_blobs.hpp\"\n\n")
        f.write("namespace kube32::embedded {\n\n")
        for i, (key, path) in enumerate(images):
            data = open(path, "rb").read()
            f.write(f"static const uint8_t img_{i}[] = {{")
            f.write(",".join(str(b) for b in data))
            f.write("};\n")
        for i, (bundle, path, full, ctype, gz) in enumerate(assets):
            data = open(full, "rb").read()
            f.write(f"static const uint8_t asset_{i}[] = {{")
            f.write(",".join(str(b) for b in data) if data else "0")
            f.write("};\n")
        f.write("\nstatic const kube32::runtime::EmbeddedImage s_images[] = {\n")
        for i, (key, path) in enumerate(images):
            f.write(f"    {{\"{key}\", img_{i}, sizeof(img_{i})}},\n")
        f.write("    {nullptr, nullptr, 0}\n};\n")
        f.write("static const EmbeddedAsset s_assets[] = {\n")
        for i, (bundle, path, full, ctype, gz) in enumerate(assets):
            size = os.path.getsize(full)
            f.write(f"    {{\"{bundle}\", \"{path}\", asset_{i}, {size}, \"{ctype}\", {'true' if gz else 'false'}}},\n")
        f.write("    {nullptr, nullptr, nullptr, 0, nullptr, false}\n};\n\n")
        f.write("const kube32::runtime::EmbeddedImage* images(size_t& count) { count = %d; return s_images; }\n" % len(images))
        f.write("const EmbeddedAsset* assets(size_t& count) { count = %d; return s_assets; }\n" % len(assets))
        f.write("\n} // namespace kube32::embedded\n")
    print(f"[embed] host: {len(images)} images, {len(assets)} assets -> {out}")


def write_esp(images, assets):
    """Firmware tables. Byte arrays in .rodata (flash) rather than EMBED_FILES,
    because the PlatformIO/ESP-IDF bridge does not run the EMBED_FILES assembly step."""
    out_dir = os.path.join(ROOT, "src", "embedded")
    os.makedirs(out_dir, exist_ok=True)
    write_host(out_dir, images, assets)
    os.replace(os.path.join(out_dir, "embedded_blobs.cpp"), os.path.join(out_dir, "embedded_blobs_esp.cpp"))
    cmake = os.path.join(out_dir, "embedded_files.cmake")
    with open(cmake, "w") as f:
        f.write("# Generated by tools/embed_assets.py. Blobs are compiled in; nothing to embed.\n")
        f.write("set(KUBE32_EMBED_FILES)\n")
    print(f"[embed] esp: {len(images)} images, {len(assets)} assets -> {out_dir}/embedded_blobs_esp.cpp")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--host-out", help="directory for the host build's generated source")
    ap.add_argument("--esp", action="store_true", help="regenerate the firmware tables")
    args = ap.parse_args()
    images, assets = collect()
    if args.host_out:
        write_host(args.host_out, images, assets)
    if args.esp:
        write_esp(images, assets)
    if not args.host_out and not args.esp:
        ap.print_help()
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
