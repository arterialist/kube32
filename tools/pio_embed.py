# PlatformIO pre-build hook: regenerate the embedded blob tables from images/,
# and the build identity GET /version reports (kube32_build_info.h, the same
# header cmake/kube32_build_info.cmake writes for CMake builds).
Import("env")
import subprocess, sys, os, time
root = env["PROJECT_DIR"]
subprocess.check_call([sys.executable, os.path.join(root, "tools", "embed_assets.py"), "--esp"])


def git(*args):
    try:
        r = subprocess.run(["git", "-C", root, *args], capture_output=True, text=True)
    except OSError:
        return None
    return r.stdout.strip() if r.returncode == 0 else None


def newest_input_mtime():
    newest = 0.0
    generated = os.path.join(root, "src", "embedded")   # rewritten by embed_assets.py on every build
    for top in ("src", "include", "cmake"):
        for dirpath, _, files in os.walk(os.path.join(root, top)):
            if dirpath == generated:
                continue
            for f in files:
                newest = max(newest, os.path.getmtime(os.path.join(dirpath, f)))
    for f in ("HEAD", "index", os.path.join("logs", "HEAD")):
        p = os.path.join(root, ".git", f)
        if os.path.exists(p):
            newest = max(newest, os.path.getmtime(p))
    return newest


gen_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")
header = os.path.join(gen_dir, "kube32_build_info.h")
os.makedirs(gen_dir, exist_ok=True)
# Rewritten when a source file or the checkout changed since the last build
if not os.path.exists(header) or newest_input_mtime() > os.path.getmtime(header):
    commit = git("rev-parse", "HEAD") or ""
    status = git("status", "--porcelain", "--untracked-files=no") if commit else None
    tree_state = "" if status is None else ("clean" if status == "" else "dirty")
    build_date = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    with open(header, "w") as f:
        f.write("// Generated by tools/pio_embed.py. Do not edit.\n#pragma once\n"
                f'#define KUBE32_GIT_COMMIT "{commit}"\n'
                f'#define KUBE32_GIT_TREE_STATE "{tree_state}"\n'
                f'#define KUBE32_BUILD_DATE "{build_date}"\n')
env.Append(CPPPATH=[gen_dir])
